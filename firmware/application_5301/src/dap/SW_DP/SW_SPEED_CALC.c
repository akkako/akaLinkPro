/* 标定点(缩放后), 按x升序: ln_x, ln_y, Q16.16 */
static const int32_t NODE_LNX[10] = { 687392, 732663, 836836, 880724, 971710, 1017136, 1030848, 1045742, 1061420, 1084528 };
static const int32_t NODE_LNY[10] = { 905413, 859987, 754511, 709085, 603609, 558183, 543559, 524705, 498133, 452707 };

#define XQ_MIN   10000u       /* 缩放后输入下限 (缩放前 10)   */
#define XQ_MAX   16000000u    /* 缩放后输入上限 (缩放前 16000) */
#define YQ_MIN   1000u
#define YQ_MAX   1000000u

/** 定点自然对数: ln(v), v >= 1, 结果 Q16.16 */
static int32_t fp_ln(uint32_t v)
{
    int e = 31 - __builtin_clz(v);        /* v = m * 2^e, m in [1,2) */
    uint32_t m = v << __builtin_clz(v);   /* Q1.31 */
    uint32_t k8   = (m >> 23) - 256;      /* mantissa-1 in [0,1) -> 0..255 */
    uint32_t frac = (m >> 15) & 0xFF;     /* 低8位做插值 */
    uint32_t f = LN_LUT[k8] +
        (uint32_t)(((uint64_t)(LN_LUT[k8+1] - LN_LUT[k8]) * frac) >> 8);
    return (int32_t)(e * LN2_Q16 + f);
}

/** 定点指数: exp(t), t 为 Q16.16, 结果 = 实际值 * 65536 */
static uint32_t fp_exp(int32_t t)
{
    uint32_t k  = (uint32_t)t / LN2_Q16;         /* t = k*ln2 + r */
    uint32_t r  = (uint32_t)t - k * LN2_Q16;     /* r in [0, ln2) */
    uint32_t f  = (uint32_t)(((uint64_t)r << 16) / LN2_Q16);  /* r/ln2, Q16.16, [0,1) */
    uint32_t j  = f >> 8;                        /* 0..255 */
    uint32_t fr = f & 0xFF;
    uint32_t g  = POW2_LUT[j] +
        (uint32_t)(((uint64_t)(POW2_LUT[j+1] - POW2_LUT[j]) * fr) >> 8);
    /* y = g * 2^k / 65536 */
    return (uint32_t)((((uint64_t)g << k) + 0x8000u) >> 16);
}

/**
 * @brief  log-log 分段线性插值
 * @param  xq 输入, 已x1000缩放, 范围 [10000, 16000000], 超范围自动钳位
 * @return yq 输出, 已x1000缩放
 */
uint32_t swd_speed_calc(uint32_t xq)
{
    if (xq < XQ_MIN) xq = XQ_MIN;
    if (xq > XQ_MAX) xq = XQ_MAX;

    int32_t lx = fp_ln(xq);
    if (lx <= NODE_LNX[0]) return YQ_MAX;   /* 低于最低标定点 */

    /* 二分查找: NODE_LNX 升序 */
    int lo = 0, hi = 9;
    while (hi - lo > 1) {
        int mid = (lo + hi) >> 1;
        if (NODE_LNX[mid] <= lx) lo = mid; else hi = mid;
    }
    if (lx >= NODE_LNX[9]) { lo = 8; hi = 9; }  /* 上端外插并入最后一段 */

    /* 区间内线性插值 */
    int32_t dx = NODE_LNX[hi] - NODE_LNX[lo];
    uint32_t frac = (uint32_t)(((uint64_t)(lx - NODE_LNX[lo]) << 16) / (uint32_t)dx);
    int32_t ly = NODE_LNY[lo] +
        (int32_t)(((int64_t)(NODE_LNY[hi] - NODE_LNY[lo]) * (int64_t)frac) >> 16);

    uint32_t yq = fp_exp(ly);
    if (yq < YQ_MIN) yq = YQ_MIN;
    if (yq > YQ_MAX) yq = YQ_MAX;
    return yq;
}
